// Read-only real desktop regression: existing DWG task, no uploads, model calls or NX.
// Changes only temporary view controls and restores them; frozen task evidence must stay identical.
import assert from 'node:assert/strict'
import * as fs from 'node:fs/promises'
import path from 'node:path'
import { createRequire } from 'node:module'
const { chromium } = createRequire(import.meta.url)(process.env.CAMIND_PLAYWRIGHT_PATH || 'playwright-core')
const browser = await chromium.connectOverCDP('http://127.0.0.1:9236')
try {
  const page = browser.contexts()[0].pages().find(p => p.url().startsWith('dsh-app:'))
  assert(page, 'A freshly started real desktop is required')
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const sid = await page.locator('[data-conversation-session]').first().getAttribute('data-conversation-session')
  const task = () => page.evaluate(async sid => (await (await fetch(`/camind/api/cam/tasks/${sid}`)).json()).data, sid)
  const before = await task(); assert(before.inputs.dwg, 'Select an existing task with a DWG before running')
  assert.equal((await page.locator('[contenteditable="true"]').first().innerText()).trim(), '', 'Use an empty draft; selection tests never overwrite user text')
  const wasWorkbench = await page.locator('.wb-main').count() > 0
  if (!wasWorkbench) await page.getByRole('tab', { name: '工作台', exact: true }).click()
  const model = page.getByRole('button', { name: '3D 模型', exact: true })
  const wasModel = await model.getAttribute('aria-pressed') === 'true'
  await page.getByRole('button', { name: 'CAD 图纸', exact: true }).click()
  const host = page.locator('.wb-drawing-svg'), svg = host.locator(':scope > svg')
  await svg.waitFor({ timeout: 90000 })
  const readView = () => svg.evaluate(el => { const b = el.viewBox.baseVal; return { x: b.x, y: b.y, width: b.width, height: b.height } })
  const previousView = await readView()
  const tools = page.locator('.wb-drawing-tools')
  const fit = () => tools.getByRole('button', { name: '适配全图 (F)', exact: true }).click()
  const colorToggle = tools.getByRole('checkbox', { name: '原始配色', exact: true })
  let previousColor = false
  try {
    assert.equal(await page.locator('.wb-drawing-annotations').count(), 0, 'Annotations start collapsed')
    assert.equal(await svg.locator(':scope > rect[fill="#23272e"]').count(), 0, 'Background is not drawing geometry')
    assert(!(await page.locator('.wb-drawing-stage').innerText()).includes('dwg2dxf'))
    assert.equal(await page.locator('.wb-drawing-warning, .wb-drawing-controls > details').count(), 0, 'Status does not sit beside drawing tools')
    const preview = await page.evaluate(async sid => (await (await fetch(`/camind/api/cam/tasks/${sid}/drawing`)).json()).data, sid)
    assert.equal(preview.preview_partial, false, 'The real fixture has only dimension helper omissions')
    assert.equal(await page.locator('.wb-preview-status').count(), 0, 'Dimension helpers do not create a title warning')
    await tools.locator(':scope > details').evaluate(el => { el.open = false; for (const detail of el.querySelectorAll('details')) detail.open = false })
    await tools.getByLabel('更多图纸选项', { exact: true }).click()
    await tools.getByText('转换详情', { exact: true }).click()
    await tools.getByText('已省略 167 个标注辅助点，不作为图纸内容显示。', { exact: true }).waitFor()
    const diagnostic = tools.getByRole('textbox', { name: '转换诊断信息，可复制' })
    assert.equal(await diagnostic.isVisible(), false, 'Internal codes start folded away')
    await tools.getByText('诊断信息', { exact: true }).click()
    assert((await diagnostic.inputValue()).includes('ignored_dimension_defpoint'))
    await diagnostic.press('Escape')
    await fit()
    const initial = await readView(), r = await host.boundingBox()
    assert(r.width > 100 && r.height > 100)
    const p = { x: Math.round(r.x + r.width * .35), y: Math.round(r.y + r.height * .35) }
    const world = p => svg.evaluate((el, p) => { const point = el.createSVGPoint(); point.x = p.x; point.y = p.y; const q = point.matrixTransform(el.getScreenCTM().inverse()); return { x: q.x, y: q.y } }, p)
    const anchor = await world(p)
    await page.mouse.move(p.x, p.y); await page.mouse.wheel(0, -100)
    await page.waitForFunction(old => document.querySelector('.wb-drawing-svg > svg').viewBox.baseVal.width < old, initial.width)
    const afterAnchor = await world(p)
    assert(Math.abs(anchor.x - afterAnchor.x) < initial.width * 1e-5)
    assert(Math.abs(anchor.y - afterAnchor.y) < initial.width * 1e-5, 'Zoom stays at the mouse')
    const zoomed = await readView()
    await page.evaluate(() => getSelection().removeAllRanges())
    await page.mouse.move(p.x, p.y); await page.mouse.down(); await page.mouse.move(p.x + 70, p.y + 40, { steps: 8 }); await page.mouse.up()
    assert.equal(await page.evaluate(() => getSelection().toString()), '', 'Pan must not select SVG or page text')
    const panned = await readView(); assert(panned.x < zoomed.x); assert.equal(panned.width, zoomed.width)
    assert.equal(await host.getAttribute('data-dragging'), 'false')
    await tools.getByRole('button', { name: '框选放大', exact: true }).click()
    await page.mouse.move(r.x + r.width * .25, r.y + r.height * .3); await page.mouse.down()
    await page.mouse.move(r.x + r.width * .65, r.y + r.height * .65, { steps: 8 }); await page.mouse.up()
    assert((await readView()).width < panned.width)
    assert.equal(await tools.getByRole('button', { name: '框选放大', exact: true }).getAttribute('aria-pressed'), 'false')
    await tools.getByRole('button', { name: '框选放大', exact: true }).click(); await page.keyboard.press('Escape')
    assert.equal(await host.getAttribute('data-box'), 'false')
    await host.focus(); await page.keyboard.press('f')
    const keyboardFit = await readView()
    assert(Math.abs(keyboardFit.width - initial.width) < initial.width * 1e-5, `Keyboard fit ${keyboardFit.width} versus initial ${initial.width}`)
    await page.keyboard.press('+'); assert((await readView()).width < initial.width)
    const beforeArrow = await readView(); await page.keyboard.press('ArrowRight')
    assert((await readView()).x > beforeArrow.x, 'Keyboard panning remains available')
    await tools.getByRole('button', { name: '框选放大', exact: true }).click()
    await host.dispatchEvent('pointercancel', { pointerId: 1 })
    assert.equal(await host.getAttribute('data-box'), 'false', 'Cancellation clears box mode')
    const fineLine = await svg.locator('[stroke-width]').first().evaluate(el => Number.parseFloat(getComputedStyle(el).strokeWidth) * Math.hypot(el.getScreenCTM().a, el.getScreenCTM().b))
    assert(fineLine >= .84, 'Thin lines retain a readable screen width')
    if (await model.isEnabled()) {
      const view = await readView()
      await model.click(); await page.getByRole('button', { name: 'CAD 图纸', exact: true }).click()
      assert.deepEqual(await readView(), view, '3D/2D switching must preserve the drawing viewport')
    }
    const annotationButton = tools.getByRole('button', { name: '查找图纸文字', exact: true })
    await annotationButton.click()
    const aside = page.locator('.wb-drawing-annotations')
    const search = aside.getByRole('textbox', { name: '搜索图纸文字' })
    await search.fill('')
    assert.equal(await aside.locator('.wb-drawing-annotation-list > button').count(), 0, 'Empty search does not dump hundreds of fragments')
    await search.fill('85')
    await aside.locator('.wb-drawing-annotation-list > button').first().click()
    await page.locator('[data-composer-chip="cam-drawing"]').waitFor()
    assert(await page.locator('.wb-drawing-selected').count() > 0)
    await page.locator('.wb-drawing-focus').waitFor()
    assert.equal(await aside.locator('.wb-drawing-annotation-list > button[aria-pressed="true"]').count(), 1)
    const beforeSearch = await readView()
    await search.fill('f-no-matching-annotation'); await search.press('f')
    assert.deepEqual(await readView(), beforeSearch, 'Input keys must not trigger canvas shortcuts')
    await aside.getByText('没有匹配的内容', { exact: true }).waitFor()
    await search.press('Escape'); assert.equal(await aside.count(), 0)
    await tools.getByLabel('更多图纸选项', { exact: true }).click()
    previousColor = await colorToggle.isChecked()
    await colorToggle.check()
    const blue = await svg.locator('[fill="#0000ff"],[stroke="#0000ff"]').count()
    assert(blue > 0, 'Real drawing must contain the original ACI blue')
    await colorToggle.uncheck()
    assert.equal(await svg.locator('[fill="#0000ff"],[stroke="#0000ff"]').count(), 0)
    await colorToggle.press('Escape')
    await fit()
    const safe = await svg.evaluate(el => {
      const b = el.getBBox(), m = el.getScreenCTM(), a = new DOMPoint(b.x, b.y).matrixTransform(m), z = new DOMPoint(b.x + b.width, b.y + b.height).matrixTransform(m)
      const toolbar = el.closest('.wb-drawing-stage').querySelector('.wb-drawing-tools').getBoundingClientRect()
      const composer = el.closest('.wb-main').querySelector('.wb-floating-composer')?.getBoundingClientRect()
      return { top: a.y, bottom: z.y, toolbarBottom: toolbar.bottom, composerTop: composer?.top }
    })
    assert(safe.top > safe.toolbarBottom, 'Fit avoids the toolbar')
    if (safe.composerTop) assert(safe.bottom < safe.composerTop, 'Fit avoids the floating composer')
    const cdp = await page.context().newCDPSession(page)
    try {
      for (const width of [1024, 736, 360]) {
        await cdp.send('Emulation.setDeviceMetricsOverride', { width, height: 768, deviceScaleFactor: 1, mobile: false })
        await fit()
        const fits = await page.locator('.wb-drawing-stage').evaluate(el => { const stage = el.getBoundingClientRect(), tools = el.querySelector('.wb-drawing-tools').getBoundingClientRect(); return stage.width > 0 && tools.right <= stage.right && tools.left >= stage.left })
        assert(fits, `Floating toolbar fits at ${width}px`)
      }
    } finally { await cdp.send('Emulation.clearDeviceMetricsOverride'); await cdp.detach() }
    await fit()
    assert.deepEqual(await task(), before, 'Viewing must not mutate task/evidence/authorization')
    assert.deepEqual(errors, [])
    const dir = path.resolve('.dsh/workbench-acceptance'); await fs.mkdir(dir, { recursive: true })
    await page.screenshot({ path: path.join(dir, 'drawing-optimized.png') })
    await fs.writeFile(path.join(dir, 'drawing-report.json'), JSON.stringify({ source: 'real desktop / existing task', anchored_zoom: true, no_text_selection: true, box_zoom: true, keyboard: true, view_preserved: true, readable_colors: true, safe_fit: true, helper_omissions_not_warning: true, diagnostics_folded: true, frozen_task_unchanged: true, pageerrors: errors }, null, 2))
    console.log('drawing desktop acceptance: PASS (real DWG, no model calls/NX/task changes)')
  } finally {
    if (await page.locator('[data-composer-chip="cam-drawing"]').count()) { await host.focus(); await page.keyboard.press('Escape') }
    await svg.evaluate((el, b) => {
      el.setAttribute('viewBox', `${b.x} ${b.y} ${b.width} ${b.height}`)
      const m = el.getScreenCTM(); el.style.setProperty('--wb-min-stroke', `${.85 / Math.hypot(m.a, m.b)}px`)
    }, previousView)
    if (await page.locator('.wb-drawing-annotations').count()) await page.getByRole('button', { name: '收起图纸文字搜索' }).click()
    if (await colorToggle.isVisible()) await colorToggle.setChecked(previousColor)
    await tools.locator(':scope > details').evaluate(el => { el.open = false })
    if (wasModel && await model.isEnabled()) await model.click()
    if (!wasWorkbench) await page.getByRole('tab', { name: '对话', exact: true }).click()
  }
} finally { await browser.close() }
